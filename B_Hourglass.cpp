void solve(){
    lli s,k,m;
    cin>>s>>k>>m;
    lli flips=m/k;
    if(flips&1){
        lli left=min(s,k);
        lli time=m%k;
        lli rem=left-time;
        if(rem>0) cout<<rem<<endl;
        else cout<<0<<endl;
    }
    else{
        lli left=s;
        lli time=m%k;
        lli rem=left-time;
        cout<<max(0LL,rem)<<endl;
    }
}
