const lli N=2e5+10;
const lli M=998244353;

lli binExpItr(lli a,lli b){
    lli ans=1;
    while(b>0){
        if(b&1) ans=(ans*a)%M;
        a=(a*a)%M;
        b>>=1;
    }
    return ans;
}
